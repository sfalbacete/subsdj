/* =====================================================================
   SubSDJ · Room — the SPACE: «tape» ping-pong delay, convolution
   reverb (IR generated by code), limiter, master and analyser.
   SEND/RETURN model, like the multitimbral synths of the 90s: each engine
   sends it its dry signal (the mix) and two sends — how much of it goes to
   the delay and how much to the reverb. The Room is ONE: size, damp, echo
   time, BPM… Four musicians in a room: each one decides how far from the
   mic they stand; none of them decides the size of the room.
     · usual mode: each AudioEngine creates its own and sounds as always
       (a send with return at 1 ≡ the old wet, by linearity; the echoes
       enter the reverb through `dlyToRev` = reverbMix, as before).
     · Parts mode (engine/parts.js): ONE Room shared by the parts.
   ROOM_KEYS = PARAMS keys that belong to the Room, not to the instrument: in
   Parts mode the rack edits them for all the parts at once and presets
   don't touch them (registry.loadState skips them). `engines` = hooked
   engines: set() keeps their S in sync (Arp/Seq/WaveSeq read the S.bpm of
   their own engine: a single clock for the scene).
   ===================================================================== */
import { makeIR, mkLFO, setLfoShape } from './nodes.js';

// Output limiter (see worklets/limiter-processor.js): same delay (6 ms) and
// same gain below the threshold (+1.71 dB, measured) as the DynamicsCompressor
// it replaces; a true ceiling at −1 dBFS; release as before.
export const LIM_LOOKAHEAD = 0.006, LIM_CEIL_DB = -1, LIM_MAKEUP_DB = 1.71, LIM_RELEASE = 0.1;
// Fixed headroom in front of the limiter (1.1.0). Before, each voice was so loud that a
// single note already brushed the ceiling, and a pad chord overshot it by 4-8 dB: the limiter
// clipped the whole sustain and its gain went up and down with the beating peaks of the
// detuned saws (the «dirty chord, with ups and downs» Sergio heard).
// With this headroom a four-note pad chord doesn't touch it: the limiter is a
// safety net again. Calibrated by measuring the factory presets.
export const HEADROOM_DB = -9;

export const ROOM_KEYS = new Set(['bpm', 'swing', 'dlyTime', 'dlySync', 'dlyDamp', 'dlyWow', 'dlySat',
                                  'reverbSize', 'reverbDamp', 'reverbPre', 'reverbType', 'shimAmt', 'shimInt',
                                  'tapeSat', 'tapeWow']);

// Shimmer (Roadmap 5.0 · block 3): loop tail → HP → LP → pitch shifter
// (worklets/shift-processor.js) → ×gain → reverb input. Each lap raises
// the chosen interval: the tail becomes a rising choir (Eno/Lanois).
// The loop gain is CALIBRATED against the reverb's energy: a reverb returns
// much less energy than goes in (the IR normalized by WebAudio has a fixed
// RMS of 0.00126 → energy ≈ 0.07·Size; the plate, measured in Node with an
// impulse, from 0.08 at Size 1 to 0.54 at Size 20), so with a fixed gain
// each lap lost ~9 dB and there was no choir. With g = √(amt·SHIM_LOOP_MAX / G)
// the energy per lap is amt·SHIM_LOOP_MAX whatever the Size and the type: at
// max, 0.8 < 1 (stable; the steady-state build-up is 1/(1−0.8) = ×5 in
// energy, which the Mix knob and the limiter absorb), and turning Size
// doesn't matter. HP/LP in the loop: no lows piling up lap after lap, and the
// spectrum entering the shifter is bounded (at +12 what goes in at 5 kHz
// comes out at 10 kHz: there the octave ladder dies out by itself).
const SHIM_LOOP_MAX = 0.8, SHIM_G_MAX = 8, SHIM_HP = 120, SHIM_LP = 5000;
const IR_G_PER_S = 0.0699;   // 44100 · 0.00125893²: the ConvolverNode's normalization constant
const PLATE_G = [[0.5, 0.075], [1, 0.082], [2, 0.114], [4, 0.189], [8, 0.351], [12, 0.409], [20, 0.538]];   // measured (damp 0)
const tableAt = (tab, x) => {
  if (x <= tab[0][0]) return tab[0][1];
  for (let i = 1; i < tab.length; i++) { const [x0, y0] = tab[i - 1], [x1, y1] = tab[i]; if (x <= x1) return y0 + (y1 - y0) * (x - x0) / (x1 - x0); }
  return tab[tab.length - 1][1];
};
export const reverbEnergyGain = (type, size) => type === 'plate' ? tableAt(PLATE_G, size) : IR_G_PER_S * size;
// Freeze: the plate at decay FREEZE_DECAY (a hair below 1: the tank is almost
// lossless and the tail takes ~half an hour to drop 60 dB) with the INPUT closed:
// whatever was playing stays. Only the plate has state to freeze (the IR is a
// FIR: it retains nothing). Closing the input also cuts the shimmer loop:
// feeding back into a lossless tank would grow without limit.
export const FREEZE_DECAY = 0.9995;

// Tape on the MASTER (Roadmap 5.0 · block 7): sum (dry + returns) →
// soft saturation → wow/flutter → limiter. The «degraded glue» of
// Arnalds, Frahm or Guðnadóttir: the whole mix goes through the same tape, so
// the parts blend together. Both stages are EXACTLY transparent at 0
// (dry paths at gain 1 and wet ones at 0: the usual renders don't change by
// a single sample; wow at 0 doesn't even add its latency).
// Revision after LISTENING (Sergio, 2026-10-03): the first version (knee
// k = 2, input ×3) «crackled» with a three-note chord — it was
// intermodulation: with the sub at −1 the mix peak goes above 1.5 and that, with
// that curve, is already hard clipping, not tape. Now the curve is plain tanh(x)
// (slope 1 at the origin: a small signal comes out as it goes in), the input rises
// at most ×2 and the knob enters SQUARED (the lower half is just color; the
// upper, compression). Wow at ±7 ct wasn't audible on a pad that already has ±7
// detune and ensemble: now ±25 ct at max. The fixed hiss was REMOVED: a noise that
// doesn't react to what you play adds nothing (the air that follows the notes is
// already given by each voice's Noise knob).
const TAPE_SAT_DRIVE = 1;         // input gain at max: 1 + DRIVE·sat² = ×2 (+6 dB)
const TAPE_SAT_MAKEUP = 0.52;     // 1/(1 + 0.52·sat²): at max, a sine of peak 0.5 comes out at the same level (tanh(1)·0.656 = 0.5)
const TAPE_LP_MIN = 8000;         // Hz: tape loses highs when it saturates (log from 20 kHz to this)
const TAPE_DLY = 0.008;           // s: base delay of the wow line (larger than the maximum excursion)
// Wow: the pitch deviation is the DERIVATIVE of the delay (2π·f·d). With the
// 'drift' shape (components 0.375…1.625 × f, normalized to ±1) and 6 ms at 0.8 Hz
// it gives ≈ ±40 ct at max: at max it's BROKEN tape, on purpose (at 0.3, ±12 ct, the
// wobble of a real deck). Sergio couldn't hear the 2nd version (±15 ct measured).
const TAPE_WOW_HZ = 0.8, TAPE_WOW_DEPTH = 0.006;      // irregular drift: ≈ ±40 ct at max
const TAPE_FLUT_HZ = 6.5, TAPE_FLUT_DEPTH = 0.00008;  // flutter (the capstan motor): ≈ ±6 ct
const TAPE_CURVE = (() => { const n = 2048, c = new Float32Array(n); for (let i = 0; i < n; i++) { const x = (i / (n - 1)) * 2 - 1; c[i] = Math.tanh(x); } return c; })();
const tapeLP = sat => 20000 * Math.pow(TAPE_LP_MIN / 20000, sat);
const tapePre = sat => 1 + TAPE_SAT_DRIVE * sat * sat, tapePost = sat => 1 / (1 + TAPE_SAT_MAKEUP * sat * sat);

// Plate (worklets/plate-processor.js, Dattorro): the knob's Size is an RT60 in
// seconds. MEASURED table (impulse in Node, slope of the tail between 0.5 and
// 1.5 s, damp 0): RT60 1.17 s ↔ decay 0.3 · 1.84 ↔ 0.5 (the paper's one) ·
// 2.38 ↔ 0.6 · 3.22 ↔ 0.7 · 4.72 ↔ 0.8 · 8.25 ↔ 0.9. Linear interpolation
// between points; below the first one, the formula 10^(−0.61/RT).
// LONG tails (Roadmap 5.0, Size up to 20 s): the tank's decay is not a pure
// exponential — the initial stretch falls faster (the allpass diffusion
// spreads the energy) and the late tail, slower. For what you HEAR in a 20 s
// tail the late slope rules, so the new points were measured between 1 and
// 15 s (same impulse, damp 0, mod 0.5): 16.2 s ↔ 0.93 · 21.8 ↔ 0.95 ·
// 26.3 ↔ 0.96. The first six are kept as they were (the usual presets don't
// change); between 8.25 and 16.2 the interpolation joins both measurements
// monotonically. Size 20 ↔ decay ≈ 0.943 (the worklet accepts 0.98).
const PLATE_RT = [[1.17, 0.3], [1.84, 0.5], [2.38, 0.6], [3.22, 0.7], [4.72, 0.8], [8.25, 0.9],
                  [16.2, 0.93], [21.8, 0.95], [26.3, 0.96]];
export function plateDecay(size) {
  if (size <= PLATE_RT[0][0]) return Math.pow(10, -0.611 / Math.max(0.2, size));
  for (let i = 1; i < PLATE_RT.length; i++) {
    const [s0, d0] = PLATE_RT[i - 1], [s1, d1] = PLATE_RT[i];
    if (size <= s1) return d0 + (d1 - d0) * (size - s0) / (s1 - s0);
  }
  return PLATE_RT[PLATE_RT.length - 1][1];
}
// Limits of the delay lines (fixed when the node is created): the delay reaches
// 4 s (PARAMS.dlyTime.max) plus the wow; the reverb predelay 250 ms.
export const DLY_MAX = 4.5, REV_PRE_MAX = 0.25;
const PLATE_MOD = 0.5;   // excursion of the modulated allpasses (0..1): decorrelates the modes without seasickness

// «Tape» delay: filters INSIDE the ping-pong loop and wow on the time.
// Damp sweeps (log) the LP from Nyquist to DLY_DAMP_LP_MIN and the HP from 0 Hz to
// DLY_DAMP_HP_MAX (tape/BBD: each lap loses highs and some lows).
// Wow = two slow LFOs at different L/R speeds on delayTime; at max
// ±DLY_WOW_DEPTH s => pitch deviation ≈ 2π·f·d ≈ ±1 % (about 17 ct) per repeat.
const DLY_DAMP_LP_MIN = 1200;                        // Hz: loop LP at Damp 1
const DLY_DAMP_HP_MIN = 20, DLY_DAMP_HP_MAX = 200;   // Hz: loop HP (Damp 0+ … Damp 1)
const DLY_WOW_HZ = 0.6, DLY_WOW_DEPTH = 0.0025;      // s: ±2.5 ms at Wow 1
// Maximum speed at which the echo time changes (s of delay per s): like tape, it doesn't jump.
// The read head runs at 1 − dD/dt speed: a small change (turning the knob) arrives in ~20 ms and the
// pitch slides (the dub thing); a big one (a sudden MIDI controller jump, another division, another
// BPM) sweeps smoothly instead of scraping — from 0.3 to 4 s the head covered 3.7 s of tape in 20 ms
// (pitch ×185). Below 1 the tape never runs backwards: with 0.9, lengthening the echo drops the pitch
// down to ~3 octaves (the tape braking) and shortening it raises it up to ~11 semitones.
const DLY_SLEW = 0.9;
// Runaway delay (Roadmap 7.0 · 4.1): saturation INSIDE the ping-pong loop. Each feedback branch is
// split between a clean path (1 − w) and a saturated one (w), tanh(D·x)/D: gain 1 at small signal
// (both paths sound equally loud) and ceiling 1/D. w is the Saturation, but it rises BY ITSELF when
// the feedback goes above DLY_SAT_AUTO[0]: above 1 each lap would grow without end, and with the tanh
// inside it grows until the ceiling holds it and it stays oscillating stably (the dub siren). With
// w = 0 the clean path is the usual one: the old echoes, exactly. No oversampling: the oversampling
// delay would misalign the two paths (comb) in the mix.
const DLY_SAT_AUTO = [0.9, 1];     // the saturation comes in by itself between these feedbacks (at 1, fully)
const DLY_SAT_DRIVE = 9;           // Saturation 1 → drive ×10, squared (the lower half is color; at max, dirty echoes already at −20 dBFS)
const DLY_SAT_RANGE = 8;           // the curve covers ±8 at the input (the runaway loop doesn't go above ~2)
const DLY_SAT_CURVE = (() => { const n = 8193, c = new Float32Array(n);
  for (let i = 0; i < n; i++) c[i] = Math.tanh(DLY_SAT_RANGE * (2 * i / (n - 1) - 1)); return c; })();

export class Room {
  // S: state with the ROOM_KEYS (single mode: the engine's own S; Parts
  // mode: the scene's state). fb = delay feedback (single mode: follows
  // the Amount knob, as always; Parts: a Room knob).
  // dlyToRev = how much echo goes into the reverb (single mode = reverbMix).
  constructor(ctx, S, { fb = 0.45, dlyToRev = 0.5, master = 0.7, dest = ctx.destination } = {}) {
    this.ctx = ctx; this.S = S;
    this.engines = [];                               // engines whose S is kept in sync

    // --- Inputs ---
    this.dry = ctx.createGain();                     // dry mix of the engines
    this.dlyIn = ctx.createGain();                   // delay send: summed to mono (the ping-pong starts from the center)
    this.dlyIn.channelCount = 1; this.dlyIn.channelCountMode = 'explicit';
    this.revIn = ctx.createGain();                   // reverb send (stereo)
    this.sum = ctx.createGain();                     // dry + returns

    // --- Ping-pong delay (stereo): the echoes bounce L<->R ---
    this.dlyL = ctx.createDelay(DLY_MAX); this.dlyL.delayTime.value = this._dlyT = this._effDelay();
    this.dlyR = ctx.createDelay(DLY_MAX); this.dlyR.delayTime.value = this._effDelay();
    this.ppFbL = ctx.createGain(); this.ppFbR = ctx.createGain();
    this.ppFbL.gain.value = this.ppFbR.gain.value = fb;
    this._fb = fb;
    // loop saturation (see DLY_SAT_*): clean (1 − w) + tanh(D·x)/D (w), in each branch
    const mkSat = () => {
      const dry = ctx.createGain(), pre = ctx.createGain(), sh = ctx.createWaveShaper(), post = ctx.createGain(), wet = ctx.createGain();
      sh.curve = DLY_SAT_CURVE; pre.connect(sh); sh.connect(post); post.connect(wet);
      return { dry, pre, sh, post, wet };
    };
    this.fbSatL = mkSat(); this.fbSatR = mkSat();
    this._dlySatGains((p, v) => { p.value = v; });
    this.ppMerge = ctx.createChannelMerger(2);
    this.dlRet = ctx.createGain();                   // return at 1: the level is set by each part's SEND
    // «Tape»: Butterworth LP+HP (Q in dB: −3 = flat) at the INPUT of each
    // line — so the 1st repeat already goes once through the filter, the 2nd twice…
    // like the tape/BBD echo, which darkens on every lap. At Damp 0 the LP is
    // set at Nyquist and the HP at 0 Hz: the WebAudio biquad reduces them to the
    // exact IDENTITY (unit coefficients), the usual presets don't change.
    const dampF = this._dampFreqs(S.dlyDamp);
    const mkDamp = () => {
      const lp = ctx.createBiquadFilter(); lp.type = 'lowpass';  lp.Q.value = -3; lp.frequency.value = dampF.lp;
      const hp = ctx.createBiquadFilter(); hp.type = 'highpass'; hp.Q.value = -3; hp.frequency.value = dampF.hp;
      lp.connect(hp); return { lp, hp };
    };
    this.dampL = mkDamp(); this.dampR = mkDamp();
    // wow: two slow LFOs at different L/R speeds (decorrelated: each
    // ping-pong bounce detunes differently and the echo widens)
    this.wowL = mkLFO(ctx, DLY_WOW_HZ, S.dlyWow * DLY_WOW_DEPTH);        this.wowL.depth.connect(this.dlyL.delayTime);
    this.wowR = mkLFO(ctx, DLY_WOW_HZ * 1.13, S.dlyWow * DLY_WOW_DEPTH); this.wowR.depth.connect(this.dlyR.delayTime);

    // --- Convolution reverb (generated IR). TWO convolvers in A/B: the new IR
    // goes in through the one that is off and crossfades in ~50 ms, without
    // abruptly cutting the previous one's tail. Predelay: DelayNode before the
    // convolvers (separates the attack from the tail). ---
    this.revPre = ctx.createDelay(REV_PRE_MAX); this.revPre.delayTime.value = S.reverbPre;
    this.convA = ctx.createConvolver(); this.convA.buffer = makeIR(ctx, S.reverbSize, 2.5, S.reverbDamp);
    this.convB = ctx.createConvolver();
    this.revXA = ctx.createGain(); this.revXA.gain.value = 1;
    this.revXB = ctx.createGain(); this.revXB.gain.value = 0;
    this._revFront = 'A'; this._irStale = false;
    // Two reverbs to choose from (reverbType): «hall» = convolution with the noise
    // IR; «plate» = algorithmic (Dattorro worklet, created when it is chosen).
    // Crossfade between both; only the active one gets input (the other costs nothing).
    this.irMix = ctx.createGain(); this.irMix.gain.value = S.reverbType === 'plate' ? 0 : 1;
    this.plateMix = ctx.createGain(); this.plateMix.gain.value = S.reverbType === 'plate' ? 1 : 0;
    this.plate = null;
    this.revRet = ctx.createGain();                  // return at 1 (same: the level is set by the send)
    this.dlyToRev = ctx.createGain(); this.dlyToRev.gain.value = dlyToRev;   // echo → reverb (the echoes live in the Room)

    // --- Output limiter -> master -> analyser ---
    // Brickwall with 6 ms lookahead (worklets/limiter-processor.js): it never lets
    // anything through above LIM_CEIL_DB and spreads the gain reduction over the
    // lookahead (without the harshness of the old DynamicsCompressor when pushed).
    // Below the ceiling it is linear with +1.71 dB: the same that one added.
    this.comp = new AudioWorkletNode(ctx, 'limiter-processor', { numberOfInputs: 1, numberOfOutputs: 1, outputChannelCount: [2],
      processorOptions: { lookahead: LIM_LOOKAHEAD, ceilingDb: LIM_CEIL_DB, makeupDb: LIM_MAKEUP_DB, release: LIM_RELEASE } });
    this.headroom = ctx.createGain(); this.headroom.gain.value = Math.pow(10, HEADROOM_DB / 20);
    this.master = ctx.createGain(); this.master.gain.value = master;
    this.analyser = ctx.createAnalyser(); this.analyser.fftSize = 2048; this.analyser.smoothingTimeConstant = 0.8;

    // --- Tape on the master (see constants TAPE_*): two stages, each exact at 0 ---
    this.tapeIn = ctx.createGain();
    // 1) dry/wet saturation
    this.satDry = ctx.createGain(); this.satDry.gain.value = 1 - S.tapeSat;
    this.satPre = ctx.createGain(); this.satPre.gain.value = tapePre(S.tapeSat);
    this.satShaper = ctx.createWaveShaper(); this.satShaper.curve = TAPE_CURVE; this.satShaper.oversample = '2x';
    this.satPost = ctx.createGain(); this.satPost.gain.value = tapePost(S.tapeSat);
    this.satLP = ctx.createBiquadFilter(); this.satLP.type = 'lowpass'; this.satLP.Q.value = -3; this.satLP.frequency.value = tapeLP(S.tapeSat);
    this.satWet = ctx.createGain(); this.satWet.gain.value = S.tapeSat;
    this.satOut = ctx.createGain();
    // 2) wow/flutter: short line modulated by an irregular drift ('drift' buffer) and a fast sine;
    //    at 0 the dry path goes through whole (no latency, no phase); with wow > 0 everything goes through the line
    const wowOn = S.tapeWow > 0 ? 1 : 0;
    this.wowDry = ctx.createGain(); this.wowDry.gain.value = 1 - wowOn;
    this.wowWet = ctx.createGain(); this.wowWet.gain.value = wowOn;
    this.tapeDelay = ctx.createDelay(0.02); this.tapeDelay.delayTime.value = TAPE_DLY;
    this.tapeWowLFO = mkLFO(ctx, TAPE_WOW_HZ, S.tapeWow * TAPE_WOW_DEPTH); setLfoShape(ctx, this.tapeWowLFO, 'drift');
    this.tapeFlutLFO = mkLFO(ctx, TAPE_FLUT_HZ, S.tapeWow * TAPE_FLUT_DEPTH);
    this.tapeWowLFO.depth.connect(this.tapeDelay.delayTime); this.tapeFlutLFO.depth.connect(this.tapeDelay.delayTime);
    this.tapeOut = ctx.createGain();

    // --- Connections ---
    this.dry.connect(this.sum);
    this.dlyIn.connect(this.dampL.lp);                                        // mono send -> tape filter -> L line
    this.dampL.hp.connect(this.dlyL); this.dampR.hp.connect(this.dlyR);
    this.dlyL.connect(this.ppMerge, 0, 0);                                    // dlyL -> left channel
    this.dlyR.connect(this.ppMerge, 0, 1);                                    // dlyR -> right channel
    this.dlyL.connect(this.ppFbL); this.dlyR.connect(this.ppFbR);
    for (const [fb, sat, damp] of [[this.ppFbL, this.fbSatL, this.dampR], [this.ppFbR, this.fbSatR, this.dampL]]) {
      fb.connect(sat.dry); sat.dry.connect(damp.lp);                         // crossed feedback L->R / R->L (filtered again)…
      fb.connect(sat.pre); sat.wet.connect(damp.lp);                         // …clean and saturated, mixed by w
    }
    this.ppMerge.connect(this.dlRet); this.dlRet.connect(this.sum);
    this.dlRet.connect(this.dlyToRev); this.dlyToRev.connect(this.revIn);     // the echoes reverberate too
    this.revIn.connect(this.revPre);
    this.convA.connect(this.revXA); this.revXA.connect(this.irMix);          // (convB gets no input until the first Size/Damp change)
    this.convB.connect(this.revXB); this.revXB.connect(this.irMix);
    this.irMix.connect(this.revRet); this.plateMix.connect(this.revRet);
    if (S.reverbType === 'plate') { this._ensurePlate(); this.revPre.connect(this.plate); }
    else this.revPre.connect(this.convA);
    this.revRet.connect(this.sum);
    // sum → tape (saturation → wow) → headroom → master → limiter → analyser. The
    // master goes BEFORE the limiter (1.1.0): turning it down takes work off it (clean) and
    // turning it up pushes it (louder, compressed). It was tried this way on 2026-10-12 and
    // reverted because the DynamicsCompressor of that time let peaks through («16 notes»
    // clipped +0.3 dB); the current limiter is brickwall with lookahead: |y| ≤ ceiling.
    // The tape sits before the headroom: its saturation sees the same level as always.
    this.sum.connect(this.tapeIn);
    this.tapeIn.connect(this.satDry); this.satDry.connect(this.satOut);
    this.tapeIn.connect(this.satPre); this.satPre.connect(this.satShaper); this.satShaper.connect(this.satPost);
    this.satPost.connect(this.satLP); this.satLP.connect(this.satWet); this.satWet.connect(this.satOut);
    this.satOut.connect(this.wowDry); this.wowDry.connect(this.tapeOut);
    this.satOut.connect(this.tapeDelay); this.tapeDelay.connect(this.wowWet); this.wowWet.connect(this.tapeOut);
    this.tapeOut.connect(this.headroom); this.headroom.connect(this.master); this.master.connect(this.comp);
    this.comp.connect(this.analyser); this.analyser.connect(dest);

    // --- Shimmer (on demand: the common case shimAmt = 0 doesn't pay for the worklet) and freeze ---
    this.shim = null; this.frozen = false;
    if (S.shimAmt > 0) this._ensureShim();
  }

  // ---------- shimmer ----------
  _shimSemis() { return parseInt(this.S.shimInt, 10) || 12; }
  // loop gain (amplitude) so that the energy per lap is amt·SHIM_LOOP_MAX
  _shimGain() {
    const G = reverbEnergyGain(this.S.reverbType, this.S.reverbSize);
    return Math.min(SHIM_G_MAX, Math.sqrt(this.S.shimAmt * SHIM_LOOP_MAX / Math.max(1e-3, G)));
  }
  _shimUpdate(smooth) { if (this.shim) smooth(this.shim.fb.gain, this._shimGain()); }
  _ensureShim() {
    if (this.shim) return this.shim;
    const ctx = this.ctx;
    const hp = ctx.createBiquadFilter(); hp.type = 'highpass'; hp.Q.value = -3; hp.frequency.value = SHIM_HP;
    const lp = ctx.createBiquadFilter(); lp.type = 'lowpass';  lp.Q.value = -3; lp.frequency.value = SHIM_LP;
    const shift = new AudioWorkletNode(ctx, 'shift-processor', { numberOfInputs: 1, numberOfOutputs: 1, outputChannelCount: [2] });
    shift.parameters.get('semitones').value = this._shimSemis();
    const fb = ctx.createGain(); fb.gain.value = this._shimGain();
    this.revRet.connect(hp); hp.connect(lp); lp.connect(shift); shift.connect(fb); fb.connect(this.revIn);   // revIn: with freeze it closes and cuts the loop
    return this.shim = { hp, lp, shift, fb };
  }
  // Freeze (plate only). Optional `at` on the audio clock (used by the selftest).
  // Returns whether anything changed: with the IR there is no state to freeze and it does nothing.
  setFreeze(on, at = null) {
    on = !!on;
    if (on === this.frozen) return false;
    if (on && this.S.reverbType !== 'plate') return false;
    this.frozen = on;
    const t = at !== null ? at : this.ctx.currentTime;
    this.revIn.gain.setTargetAtTime(on ? 0 : 1, t, 0.05);
    this._ensurePlate().parameters.get('decay').setTargetAtTime(on ? FREEZE_DECAY : plateDecay(this.S.reverbSize), t, 0.05);
    return true;
  }

  // Room keys (ROOM_KEYS): updates the state of ALL the hooked engines
  // (a single BPM, a single Room) and applies it to the graph.
  set(name, value) {
    this.S[name] = value;
    for (const e of this.engines) e.S[name] = value;
    const now = this.ctx.currentTime, smooth = (p, v) => p.setTargetAtTime(v, now, 0.02);
    switch (name) {
      case 'dlyDamp': { const f = this._dampFreqs(value);
        [this.dampL, this.dampR].forEach(d => { smooth(d.lp.frequency, f.lp); smooth(d.hp.frequency, f.hp); }); break; }
      case 'dlyWow': smooth(this.wowL.depth.gain, value * DLY_WOW_DEPTH); smooth(this.wowR.depth.gain, value * DLY_WOW_DEPTH); break;
      case 'dlySat': this._dlySatGains(smooth); break;
      case 'dlyTime':                                      // with sync on, the bpm rules, not the knob
      case 'dlySync':
      case 'bpm': { const tt = this._effDelay(), tau = Math.max(0.02, Math.abs(tt - (this._dlyT ?? tt)) / DLY_SLEW);   // initial slope Δ/τ ≤ DLY_SLEW
        this._dlyT = tt; this.dlyL.delayTime.setTargetAtTime(tt, now, tau); this.dlyR.delayTime.setTargetAtTime(tt, now, tau); break; }
      case 'reverbPre': smooth(this.revPre.delayTime, value); break;
      case 'reverbSize':                                   // regenerating the IR is costly: we defer it (debounce)
      case 'reverbDamp':                                   // (the damp lives in the IR: same route)
        this._plateParams();                               // the plate changes instantly (they are two params)
        this._shimUpdate(smooth);                          // the shimmer loop gain follows the reverb energy (Size)
        if (this.S.reverbType === 'plate') { this._irStale = true; break; }   // the IR will be rebuilt on going back to «hall»
        clearTimeout(this._revTimer);
        this._revTimer = setTimeout(() => this._swapIR(this.S.reverbSize), 120);
        break;
      case 'reverbType': if (this.frozen && value !== 'plate') this.setFreeze(false); this._setType(value); this._shimUpdate(smooth); break;   // the IR doesn't freeze: release before switching
      // tape on the master (TAPE_*): each stage is exact at 0 again
      case 'tapeSat':
        smooth(this.satDry.gain, 1 - value); smooth(this.satWet.gain, value);
        smooth(this.satPre.gain, tapePre(value)); smooth(this.satPost.gain, tapePost(value));
        smooth(this.satLP.frequency, tapeLP(value)); break;
      case 'tapeWow': { const on = value > 0 ? 1 : 0;
        smooth(this.wowDry.gain, 1 - on); smooth(this.wowWet.gain, on);
        smooth(this.tapeWowLFO.depth.gain, value * TAPE_WOW_DEPTH); smooth(this.tapeFlutLFO.depth.gain, value * TAPE_FLUT_DEPTH); break; }
      case 'shimAmt': if (value > 0) this._ensureShim(); this._shimUpdate(smooth); break;
      case 'shimInt': if (this.shim) this.shim.shift.parameters.get('semitones').setValueAtTime(this._shimSemis(), now); break;
    }
  }

  // ---------- plate ----------
  _ensurePlate() {
    if (this.plate) return this.plate;
    this.plate = new AudioWorkletNode(this.ctx, 'plate-processor', { numberOfInputs: 1, numberOfOutputs: 1, outputChannelCount: [2] });
    this.plate.connect(this.plateMix);
    this._plateParams(true);
    return this.plate;
  }
  _plateParams(now = false) {
    if (!this.plate) return;
    const t = this.ctx.currentTime, p = this.plate.parameters;
    const put = (name, v) => { const ap = p.get(name); if (!ap) return; if (now) ap.value = v; else ap.setTargetAtTime(v, t, 0.05); };
    put('decay', this.frozen ? FREEZE_DECAY : plateDecay(this.S.reverbSize)); put('damp', this.S.reverbDamp); put('mod', PLATE_MOD);   // frozen: Size doesn't release it
  }
  _front() { return this._revFront === 'A' ? this.convA : this.convB; }
  // Reverb switch with a 50 ms fade; the input of the one fading out is
  // disconnected when it ends (a convolver or a worklet with input uses CPU).
  _setType(type) {
    const isPlate = type === 'plate', t = this.ctx.currentTime;
    if (isPlate) { this._ensurePlate(); this.revPre.connect(this.plate); }
    else if (this._irStale) { this._irStale = false; clearTimeout(this._revTimer); this._swapIR(this.S.reverbSize); }
    else this.revPre.connect(this._front());
    this.irMix.gain.setTargetAtTime(isPlate ? 0 : 1, t, 0.05);
    this.plateMix.gain.setTargetAtTime(isPlate ? 1 : 0, t, 0.05);
    clearTimeout(this._typeTimer);
    this._typeTimer = setTimeout(() => {
      const off = isPlate ? [this.convA, this.convB] : [this.plate];
      for (const n of off) { try { if (n) this.revPre.disconnect(n); } catch (e) {} }
    }, 400);
  }
  setFeedback(fb) {
    const t = this.ctx.currentTime, smooth = (p, v) => p.setTargetAtTime(v, t, 0.02);
    this._fb = fb; smooth(this.ppFbL.gain, fb); smooth(this.ppFbR.gain, fb);
    this._dlySatGains(smooth);                       // above DLY_SAT_AUTO[0], the saturation comes in by itself
  }
  // Loop saturation: w = the knob's, or the one the feedback demands; drive D from the knob
  _dlySatGains(apply) {
    const sat = +this.S.dlySat || 0, fb = this._fb || 0;
    const w = Math.max(sat, Math.min(1, Math.max(0, (fb - DLY_SAT_AUTO[0]) / (DLY_SAT_AUTO[1] - DLY_SAT_AUTO[0]))));
    const D = 1 + DLY_SAT_DRIVE * sat * sat;
    for (const s of [this.fbSatL, this.fbSatR]) {
      apply(s.dry.gain, 1 - w); apply(s.wet.gain, w);
      apply(s.pre.gain, D / DLY_SAT_RANGE); apply(s.post.gain, 1 / D);
    }
  }
  setDlyToRev(v)  { this.dlyToRev.gain.setTargetAtTime(v, this.ctx.currentTime, 0.02); }
  setMaster(v)    { this.master.gain.setTargetAtTime(v, this.ctx.currentTime, 0.02); }

  // New IR through the back convolver + crossfade; the front one is disconnected
  // when the fade ends (a convolver with input uses CPU even if its output
  // is at 0). A duplicate connect() on the same pair is harmless (it is ignored).
  _swapIR(seconds) {
    const t = this.ctx.currentTime;
    const front = this._revFront === 'A' ? { c: this.convA, g: this.revXA } : { c: this.convB, g: this.revXB };
    const back  = this._revFront === 'A' ? { c: this.convB, g: this.revXB } : { c: this.convA, g: this.revXA };
    try { back.c.buffer = makeIR(this.ctx, seconds, 2.5, this.S.reverbDamp); } catch (e) { return; }
    this.revPre.connect(back.c);
    back.g.gain.setTargetAtTime(1, t, 0.05);
    front.g.gain.setTargetAtTime(0, t, 0.05);
    clearTimeout(this._revOffTimer);
    this._revOffTimer = setTimeout(() => { try { this.revPre.disconnect(front.c); } catch (e) {} }, 400);
    this._revFront = this._revFront === 'A' ? 'B' : 'A';
  }

  // Damp 0..1 -> cutoffs of the loop filter (log sweep): LP from Nyquist to
  // DLY_DAMP_LP_MIN, HP from DLY_DAMP_HP_MIN to DLY_DAMP_HP_MAX. At exactly 0,
  // Nyquist / 0 Hz (identity in the biquad), hence the separate branch.
  _dampFreqs(d) {
    const nyq = this.ctx.sampleRate / 2;
    if (!(d > 0)) return { lp: nyq, hp: 0 };
    return { lp: nyq * Math.pow(DLY_DAMP_LP_MIN / nyq, d),
             hp: DLY_DAMP_HP_MIN * Math.pow(DLY_DAMP_HP_MAX / DLY_DAMP_HP_MIN, d) };
  }

  // Effective delay time: free (Time knob) or a musical division of the BPM
  _effDelay() {
    const div = { '1/8': 0.5, '1/8.': 0.75, '1/4': 1, '1/4.': 1.5, '1/2': 2 }[this.S.dlySync];
    return div ? Math.min(4, (60 / this.S.bpm) * div) : Math.min(4, this.S.dlyTime);   // limit = PARAMS.dlyTime.max (the line holds DLY_MAX)
  }

  // Teardown (when the scene is switched off): stops the wow LFOs and breaks the
  // feedback loop; with no live sources, the graph frees itself.
  dispose() {
    clearTimeout(this._revTimer); clearTimeout(this._revOffTimer); clearTimeout(this._typeTimer);
    for (const l of [this.wowL, this.wowR, this.tapeWowLFO, this.tapeFlutLFO]) {
      try { l.osc.stop(); l.osc.disconnect(); } catch (e) {}
      if (l.alt) { try { l.alt.stop(); l.alt.disconnect(); } catch (e) {} }   // the tape wow is a 'drift' buffer
    }
    for (const n of [this.tapeIn, this.satDry, this.satPre, this.satShaper, this.satPost, this.satLP, this.satWet, this.satOut,
                     this.wowDry, this.wowWet, this.tapeDelay, this.tapeOut]) { try { n.disconnect(); } catch (e) {} }
    if (this.plate) { try { this.plate.port.postMessage('stop'); this.plate.disconnect(); } catch (e) {} }
    try { this.comp.port.postMessage('stop'); } catch (e) {}   // the limiter is a worklet: make it stop processing
    if (this.shim) { try { this.shim.shift.port.postMessage('stop'); } catch (e) {} for (const n of [this.shim.hp, this.shim.lp, this.shim.shift, this.shim.fb]) { try { n.disconnect(); } catch (e) {} } }
    for (const s of [this.fbSatL, this.fbSatR]) for (const n of [s.dry, s.pre, s.sh, s.post, s.wet]) { try { n.disconnect(); } catch (e) {} }
    for (const n of [this.dry, this.dlyIn, this.revIn, this.sum, this.dlyL, this.dlyR, this.ppFbL, this.ppFbR,
                     this.ppMerge, this.dlRet, this.dlyToRev, this.revPre, this.convA, this.convB, this.irMix, this.plateMix,
                     this.revRet, this.headroom, this.comp, this.master, this.analyser]) { try { n.disconnect(); } catch (e) {} }
  }
}
